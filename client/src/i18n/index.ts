const translations: Record<Locale, Translations> = {
  en,
  es,
};

interface I18nStore {
  locale: Locale;
  t: Translations;
  setLocale: (locale: Locale) => void;
}

export const useI18n = create<I18nStore>((set) => ({
  locale: "en",
  t: translations.en,
  setLocale: (locale) => set({ locale, t: translations[locale] }),
}));
